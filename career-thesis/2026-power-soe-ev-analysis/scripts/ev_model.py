R=0.05
def npv(flows,r=R): return sum(f/(1+r)**(i+1) for i,f in enumerate(flows))
def path(y1,g,years=10,cap=None):
    out=[];c=y1
    for _ in range(years):
        out.append(c); c*=1+g
        if cap and c>cap: c=cap
    return out

